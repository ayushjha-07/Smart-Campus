// Helper to enrich a complaint object with default details if missing
export function enrichComplaintData(complaint) {
  const base = mockComplaintsList[0]; // fallback template
  return {
    ...base,
    ...complaint,
    department: complaint.department || 'Maintenance Department',
    assignedStaff: complaint.assignedStaff || complaint.assignedTo || 'Rajesh Kumar',
    staffRole: complaint.staffRole || 'Operations Specialist',
    staffAvatar: complaint.staffAvatar || 'RK',
    departmentEmail: complaint.departmentEmail || 'maintenance@smartcampus.demo',
    departmentPhone: complaint.departmentPhone || '+91 (080) 2854-9102',
    departmentOffice: complaint.departmentOffice || 'Campus Facility Office',
    resolutionProgress: complaint.resolutionProgress !== undefined ? complaint.resolutionProgress : (complaint.status === 'Resolved' ? 100 : 75),
    attachment: complaint.attachment || base.attachment,
    aiAnalysis: complaint.aiAnalysis || {
      category: complaint.category || 'General Maintenance',
      priority: complaint.priority || 'MEDIUM',
      confidence: 90,
      keywords: [complaint.category?.toLowerCase() || 'facility', 'campus', 'service', 'maintenance'],
      reason: 'The complaint indicates a campus facility issue that has been categorized and routed.',
      label: 'AI-generated recommendation',
    },
    timeline: complaint.timeline || base.timeline,
    statusHistory: complaint.statusHistory || base.statusHistory,
    latestUpdate: complaint.latestUpdate || base.latestUpdate,
    relatedComplaints: complaint.relatedComplaints || base.relatedComplaints,
  };
}

// Helper to look up a complaint by its ID
export function getComplaintById(id) {
  if (!id) return enrichComplaintData(mockComplaintsList[0]);

  // Check localStorage first
  try {
    const stored =
      localStorage.getItem('smart_campus_shared_complaints') ||
      localStorage.getItem('smart_campus_admin_complaints') ||
      localStorage.getItem('smart_campus_user_complaints');
    if (stored) {
      const list = JSON.parse(stored);
      const found = list.find((c) => c.id.toLowerCase() === id.toLowerCase());
      if (found) return enrichComplaintData(found);
    }
  } catch {
    // Ignore localstorage errors
  }

  // Check static mock list
  const found = mockComplaintsList.find((c) => c.id.toLowerCase() === id.toLowerCase());
  if (found) return enrichComplaintData(found);

  // Return base template with the requested id
  return enrichComplaintData({
    ...mockComplaintsList[0],
    id: id.toUpperCase(),
  });
}
